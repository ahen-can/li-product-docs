#!/usr/bin/env python3
"""Build results/light_discovery_summary.md from the results file, the master list and results/site_quirks.md.

    python3 -I scripts/build_summary.py

Tables are generated from the data; site quirks are hand-written in results/site_quirks.md and included as-is.
"""
import collections, csv, os, re

M = {m['row_id']: m for m in csv.DictReader(open('master_list.csv'))}
R = {r['row_id']: r for r in csv.DictReader(open('results/light_discovery_results.csv'))}
BLOCKED = {'icici-life', 'kotak-life', 'sud-life', 'go-digit-life'}

out = ['# Light discovery (brochure pass): summary', '',
       'Generated by `scripts/build_summary.py` from `results/light_discovery_results.csv` (one row per product) and',
       '`master_list.csv`. Hand-written notes on each site are in the last section.', '']

# ---- counts per insurer
by = collections.OrderedDict()
for m in sorted(M.values(), key=lambda x: x['insurer']):
    by.setdefault((m['insurer'], m['insurer_slug']), []).append(m)
out += ['## Counts per insurer', '',
        '| Insurer | Products | ok | of which brochure | of which policy doc | not found | manual (site blocks automation) | not run |',
        '|---|---|---|---|---|---|---|---|']
tot = collections.Counter()
for (ins, slug), rows in by.items():
    c = collections.Counter()
    for m in rows:
        r = R.get(m['row_id'])
        st = r['status'] if r else ('manual' if slug in BLOCKED else 'not run')
        c[st] += 1
        if r and st == 'ok': c[r['doc_type']] += 1
    c['n'] = len(rows); tot.update(c)
    out.append(f"| {ins} | {c['n']} | {c['ok']} | {c['brochure']} | {c['policy']} | {c['not found']} | {c['manual']} | {c['not run']} |")
out.append(f"| **Total** | **{tot['n']}** | **{tot['ok']}** | {tot['brochure']} | {tot['policy']} | **{tot['not found']}** | **{tot['manual']}** | {tot['not run']} |")
out += ['', f"Hit rate on sites that allow automated access: {tot['ok']} of {tot['n'] - tot['manual']} "
        f"({100 * tot['ok'] / max(1, tot['n'] - tot['manual']):.1f}%).", '']

# ---- odd description lines
odd = []
for rid, r in R.items():
    if r['status'] != 'ok': continue
    m = M[rid]; d = r['irdai_description_line']; why = []
    if not d: why.append('no description line found')
    else:
        if (r['linked_stated'] == 'Linked') != (m['linked_flag_uin'] == 'L'): why.append(f"linked/non-linked differs from UIN letter '{m['linked_flag_uin']}'")
        if r['par_flag_stated'] == 'not stated' and m['linked_flag_uin'] == 'N': why.append('par / non-par not stated')
        if re.search(r'micro', d, re.I): why.append('micro-insurance product')
        if re.search(r'health', d, re.I): why.append('health product')
        if re.search(r'group', d, re.I): why.append('group product')
        if re.search(r'combination|combi', r['notes'] + m['product_name'], re.I): why.append('combination product')
        if re.search(r'cipa ng|�', d): why.append('text extraction dropped ligatures ("ti")')
        if re.search(r'rider', d, re.I): why.append('mentions a rider')
    if 'OCR' in r['notes']: why.append('read by OCR from an image')
    if why: odd.append((m['insurer'], m['product_name'], m['uin'], d, '; '.join(why)))
out += ['## Description lines that look odd', '',
        'Linked ULIP lines that state no par flag (e.g. "A Unit Linked Individual Savings Life Insurance Plan") are printed that way',
        'by the insurer and are not listed here.', '',
        '| Insurer | Product | UIN | Description line (as extracted) | Why listed |', '|---|---|---|---|---|']
for o in sorted(odd):
    out.append('| ' + ' | '.join(x.replace('|', '/') for x in o) + ' |')

# ---- version differences
ver = []
for rid, r in R.items():
    if r['status'] != 'ok' or not r['uin_in_document']: continue
    m = M[rid]
    if m['uin'] and m['uin'] not in r['uin_in_document'].split(','):
        a = int(m['uin'][-2:]); b = max(int(x[-2:]) for x in r['uin_in_document'].split(','))
        ver.append((m['insurer'], m['product_name'], m['uin'], r['uin_in_document'], 'newer' if b > a else 'older', r['doc_type']))
out += ['', '## Documents whose UIN version differs from the master list', '',
        'Kept as found and never relabelled (CLAUDE.md). "Older" usually means the site has not posted the latest version;',
        '"newer" usually means the master list lags the insurer.', '',
        '| Insurer | Product | Master UIN | UIN in document | Document is | Doc type |', '|---|---|---|---|---|---|']
for v in sorted(ver):
    out.append('| ' + ' | '.join(v) + ' |')

# ---- other flags (notes)
flag = []
for rid, r in R.items():
    if r['status'] == 'ok' and re.search(r'withdrawn|same file as|letter O|combination|not on|no UIN|policy document used', r['notes'], re.I):
        flag.append((M[rid]['insurer'], M[rid]['product_name'], M[rid]['uin'] or '(none)', r['notes']))
out += ['', '## Other flags on found documents', '',
        '| Insurer | Product | UIN | Note |', '|---|---|---|---|']
for f in sorted(flag):
    out.append('| ' + ' | '.join(x.replace('|', '/') for x in f) + ' |')

# ---- not found / manual
out += ['', '## Not found / manual', '',
        'Full list with where to look: `results/manual_checklist.csv` (and `results/manual_checklist_blocked_sites.csv` for the four',
        'sites that block automated access).', '', '| Insurer | Product | UIN | Status | Where looked / reason |', '|---|---|---|---|---|']
for rid, r in sorted(R.items(), key=lambda x: (M[x[0]]['insurer'], M[x[0]]['product_name'])):
    if r['status'] == 'not found':
        out.append(f"| {M[rid]['insurer']} | {M[rid]['product_name']} | {M[rid]['uin']} | {r['status']} | {r['notes'].replace('|', '/')} |")
blocked = collections.Counter(m['insurer'] for m in M.values() if m['insurer_slug'] in BLOCKED)
out.append('| ' + ', '.join(f'{k} ({v})' for k, v in sorted(blocked.items())) + ' | all products | | manual | site blocks automated access; not attempted (brief) |')

if os.path.exists('results/site_quirks.md'):
    out += ['', open('results/site_quirks.md').read().strip()]
open('results/light_discovery_summary.md', 'w').write('\n'.join(out) + '\n')
print('written:', dict(tot))
